////// TESTBENCH DECLARATION
module CPU_pipelined_tb;
////// SIGNALS
  logic        CLK;       			  // Clock
	logic        RST;       			  // Reset
////// UUT INSTANTIATION
  CPU_pipelined uut ( CLK, RST);
////// CLOCK PARAMTERS
    localparam frequency 		= 1; //MHz             // Clock frequency
    localparam clk_period 	= (1000/frequency);    // Clock period
    localparam clk_not_clk  = (clk_period/2);      // Clock half-period
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////// ARCHITECTURE
// Clock
    initial
    begin
        CLK = 0;
    end
    always
    begin
        #clk_not_clk CLK = !CLK;
    end
  // initialize test
  initial
    begin
      RST <= 1; #clk_period; #clk_period; #clk_period; #clk_period; RST <= 0;
    end
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// END
endmodule
